public class M04ArraysIntroLab
{
	public static void main(String[] args)
	{

		int[] scores =
		{ 90, 85, 100 }; // storing multiple values

		System.out.println(scores[0]); // calling 90
		System.out.println(scores[2]); // calling 100

		scores[1] = 95;
		System.out.println(scores[1]); // calling 95
	}
}
